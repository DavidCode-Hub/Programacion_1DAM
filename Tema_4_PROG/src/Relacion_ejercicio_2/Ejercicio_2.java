package Relacion_ejercicio_2;

public class Ejercicio_2 {

	public static void main(String[] args) {
		
		for(int i = 320; i>=160; i-=20)
			System.out.println(i);
		
		int j=320;
		while(j>=160) {
			System.out.println(j);
			j-=20;
		}
		
		int k=320;
		do{
			System.out.println(k);
			k-=20;
		}while(k>=160);

	}

}
