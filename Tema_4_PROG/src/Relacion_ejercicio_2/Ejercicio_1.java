package Relacion_ejercicio_2;

public class Ejercicio_1 {

	public static void main(String[] args) {
		
		
		
		
		for(int i = 0; i<=100; i+=5)
			System.out.println(i);
		
		int j=0;
		
		while(j<=100) {
			System.out.println(j);
			j+=5;
		}
		
		int k=0;
		
		do{
			
			System.out.println(k);
			k+=5;
		}while(k<=100);
		
	}

	}


