package prueb_Objetos_ArrayList;

public class Gato {
	protected String nombre;
	protected int edad;
	protected String Raza;
	
	
	/**
	 * @param nombre
	 * @param edad
	 * @param raza
	 */
	public Gato(String nombre, int edad, String raza) {
		super();
		this.nombre = nombre;
		this.edad = edad;
		Raza = raza;
	}
	

	
}
